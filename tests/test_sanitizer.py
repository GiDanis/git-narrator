def test_is_minified_content():
    minified_line = "var a=1;" * 300
    diff = f"@@ -1,1 +1,1 @@\n+{minified_line}\n"
    assert is_minified_content(diff) is True

    normal_diff = "@@ -1,3 +1,3 @@\n+def foo():\n+    return 42\n"
    assert is_minified_content(normal_diff) is False


def test_ignore_matcher():
    matcher = IgnoreMatcher(["*.log", "secret/", "!secret/keep.txt", "temp/**/cache"])

    assert matcher.is_ignored("node_modules/pkg/index.js") is True
    assert matcher.is_ignored(".DS_Store") is True
    assert matcher.is_ignored("dist/index.html") is True
    assert matcher.is_ignored(".env.production") is True
    assert matcher.is_ignored(".env.example") is False

    assert matcher.is_ignored("error.log") is True
    assert matcher.is_ignored("nested/dir/error.log") is True
    assert matcher.is_ignored("secret/keys.json") is True
    assert matcher.is_ignored("secret/keep.txt") is False
    assert matcher.is_ignored("temp/a/b/cache") is True
    assert matcher.is_ignored("temp/cache") is True  # Zero intermediate directories

    assert matcher.is_ignored("src/models/user.py") is False


def test_is_generated_content():
    gen_diff_1 = "@@ -0,0 +1,5 @@\n+// @generated by protobuf\n+syntax = 'proto3';"
    assert is_generated_content("proto/schema.pb.go", gen_diff_1) is True

    gen_diff_2 = "@@ -0,0 +1,5 @@\n+/* Code generated by openapi-generator. DO NOT EDIT. */\n"
    assert is_generated_content("api/client.ts", gen_diff_2) is True

    # Non-comment code referencing "@generated" must NOT falsely prune real source files
    non_comment_code = '@@ -1,1 +1,2 @@\n+re.compile(r"@generated\\b")\n'
    assert is_generated_content("git_narrator/sanitizer.py", non_comment_code) is False

    normal_diff = "@@ -0,0 +1,5 @@\n+def calculate_metrics():\n+    return 100\n"
    assert is_generated_content("src/metrics.py", normal_diff) is False

    gitattributes = {
        "*.generated.ts": {"linguist-generated": "true"},
        "schema.graphql": {"diff": "false"},
    }
    assert is_generated_content("types.generated.ts", normal_diff, gitattributes=gitattributes) is True
    assert is_generated_content("schema.graphql", normal_diff, gitattributes=gitattributes) is True


def test_split_diff_into_file_chunks_including_quoted_paths():
    sample_diff = (
        "diff --git a/file1.py b/file1.py\n"
        "index 111..222 100644\n"
        "--- a/file1.py\n"
        "+++ b/file1.py\n"
        "@@ -1,1 +1,2 @@\n"
        "+# comment\n"
        'diff --git "a/my folder/file 2.py" "b/my folder/file 2.py"\n'
        "index 333..444 100644\n"
        '--- "a/my folder/file 2.py"\n'
        '+++ "b/my folder/file 2.py"\n'
        "@@ -1,1 +1,2 @@\n"
        "+# another\n"
    )
    chunks = split_diff_into_file_chunks(sample_diff)
    assert len(chunks) == 2
    assert chunks[0].file_path == "file1.py"
    assert chunks[1].file_path == "my folder/file 2.py"


def test_secret_redaction_and_deterministic_risks():
    diff = (
        "diff --git a/cfg.py b/cfg.py\n"
        "--- a/cfg.py\n"
        "+++ b/cfg.py\n"
        "@@ -1,1 +1,6 @@\n"
        '+AWS_KEY = "AKIAIOSFODNN7EXAMPLE"\n'
        '+DB_URL = "postgres://admin:super_secret_pw@db.internal:5432/prod"\n'
        '+PLACEHOLDER_SECRET = "changeme_example"\n'
        "+<<<<<<< HEAD\n"
        "+    breakpoint()\n"
    )
    redacted, findings = redact_secrets(diff, file_path="cfg.py")
    assert "AKIAIOSFODNN7EXAMPLE" not in redacted
    assert "super_secret_pw" not in redacted
    assert "[REDACTED:AWS_ACCESS_KEY]" in redacted
    assert "[REDACTED:DB_CREDENTIAL_URL]" in redacted
    assert "changeme_example" in redacted  # Placeholder preserved
    assert len(findings) == 2

    risks = scan_deterministic_risks(redacted, findings)
    cats = {r.category for r in risks}
    assert RiskCategory.SECURITY_LEAK in cats
    assert RiskCategory.CONTRACT_BREAK in cats
    assert RiskCategory.PERFORMANCE_REGRESSION in cats
    assert any(r.severity == RiskSeverity.CRITICAL for r in risks)


def test_sanitize_diff_pipeline(tmp_path: Path):
    (tmp_path / ".narratorignore").write_text("*.generated.py\nignore_me/\n", encoding="utf-8")
    (tmp_path / ".gitattributes").write_text("auto_types.ts linguist-generated=true\n", encoding="utf-8")

    diff_text = (
        "diff --git a/src/core.py b/src/core.py\n"
        "--- a/src/core.py\n"
        "+++ b/src/core.py\n"
        "@@ -1,2 +1,2 @@\n"
        "-old\n"
        "+new\n"
        "diff --git a/assets/banner.png b/assets/banner.png\n"
        "Binary files a/assets/banner.png and b/assets/banner.png differ\n"
        "diff --git a/dist/bundle.min.js b/dist/bundle.min.js\n"
        "--- a/dist/bundle.min.js\n"
        "+++ b/dist/bundle.min.js\n"
        "@@ -1,1 +1,1 @@\n"
        "+minified content\n"
        "diff --git a/auto_types.ts b/auto_types.ts\n"
        "--- a/auto_types.ts\n"
        "+++ b/auto_types.ts\n"
        "@@ -1,1 +1,1 @@\n"
        "+export type Foo = string;\n"
        "diff --git a/src/model.generated.py b/src/model.generated.py\n"
        "--- a/src/model.generated.py\n"
        "+++ b/src/model.generated.py\n"
        "@@ -1,1 +1,1 @@\n"
        "+# code\n"
    )

    result = sanitize_diff(diff_text, repo_root=tmp_path)
    assert result.kept_files == ["src/core.py"]
    assert "src/core.py" in result.cleaned_diff
    assert "assets/banner.png" not in result.cleaned_diff
    assert "dist/bundle.min.js" not in result.cleaned_diff

    pruned_map = {p.path: p.reason for p in result.pruned_files}
    assert pruned_map["assets/banner.png"] == PruneReason.BINARY
    assert pruned_map["dist/bundle.min.js"] in (PruneReason.BUILD_DIR, PruneReason.MINIFIED)
    assert pruned_map["auto_types.ts"] == PruneReason.GENERATED
    assert pruned_map["src/model.generated.py"] == PruneReason.IGNORE_RULE
